/** The state code at the end of a "City, ST" location string, when there is one. */
export function mhdStateCodeFromLocation(location: string | null | undefined): string | null {
  const match = /,\s*([A-Z]{2})\s*$/.exec(location ?? '');
  const code = match?.[1] ?? null;
  return code && MHD_US_STATES.some((state) => state.code === code) ? code : null;
}
